-- Frozen pre-ORM schema used only by upgrade compatibility tests.
CREATE TABLE IF NOT EXISTS risk_global_batch (
    project_id VARCHAR(36) NOT NULL REFERENCES risk_project(id),
    batch_id VARCHAR(128) NOT NULL,
    payload_digest CHAR(64) NOT NULL,
    accepted INT NOT NULL,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (project_id, batch_id)
);
CREATE INDEX IF NOT EXISTS idx_global_batch_expiry ON risk_global_batch(created_at);

CREATE TABLE IF NOT EXISTS risk_global_summary (
    project_id VARCHAR(36) NOT NULL REFERENCES risk_project(id),
    user_id VARCHAR(128) NOT NULL,
    bucket_at BIGINT NOT NULL,
    request_count BIGINT NOT NULL,
    failures BIGINT NOT NULL,
    denied BIGINT NOT NULL,
    suspected BOOLEAN NOT NULL,
    details_json CHARACTER LARGE OBJECT NOT NULL,
    PRIMARY KEY(project_id, user_id, bucket_at)
);
CREATE INDEX IF NOT EXISTS idx_global_summary_project_time ON risk_global_summary(project_id, bucket_at, user_id);
CREATE INDEX IF NOT EXISTS idx_global_summary_expiry ON risk_global_summary(bucket_at);

CREATE TABLE IF NOT EXISTS risk_global_state (
    project_id VARCHAR(36) NOT NULL REFERENCES risk_project(id),
    user_id VARCHAR(128) NOT NULL,
    updated_at BIGINT NOT NULL,
    state_json CHARACTER LARGE OBJECT NOT NULL,
    PRIMARY KEY(project_id, user_id)
);
CREATE INDEX IF NOT EXISTS idx_global_state_expiry ON risk_global_state(updated_at);

CREATE TABLE IF NOT EXISTS risk_global_sample (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id VARCHAR(36) NOT NULL REFERENCES risk_project(id),
    user_id VARCHAR(128) NOT NULL,
    event_id VARCHAR(128) NOT NULL,
    action VARCHAR(64) NOT NULL,
    resource_type VARCHAR(64),
    resource_id VARCHAR(256),
    route VARCHAR(256) NOT NULL,
    method VARCHAR(16) NOT NULL,
    occurred_at BIGINT NOT NULL,
    duration_ms BIGINT NOT NULL,
    response_status INT NOT NULL,
    sample_kind VARCHAR(16) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_global_sample_user_time ON risk_global_sample(project_id, user_id, occurred_at, id);
CREATE INDEX IF NOT EXISTS idx_global_sample_expiry ON risk_global_sample(occurred_at, id);

CREATE TABLE IF NOT EXISTS risk_global_sample_budget (
    minute_at BIGINT PRIMARY KEY,
    sample_count INT NOT NULL
);
